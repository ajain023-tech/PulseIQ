"""Insert the generated key-results table into README.md between RESULTS markers.

Usage: python scripts/render_results.py [--check]
Never type result numbers by hand: run `make all`, then this script.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from results_facts import ROOT, facts, pct, pp  # noqa: E402

START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def block() -> str:
    """Markdown results block (generated)."""
    f = facts()
    exp_rows = []
    for e in ("onboarding_flow_v2", "paywall_redesign", "streak_reminder"):
        exp_rows.append(
            f"| `{e}` | **{f[f'{e}_decision']}** | {pp(f[f'{e}_lift'])} "
            f"[{pp(f[f'{e}_ci_low'])}, {pp(f[f'{e}_ci_high'])}] | {f[f'{e}_srm_p']:.2g} |"
        )
    return "\n".join([
        START,
        "<!-- generated by scripts/render_results.py from artifacts/ - do not edit by hand -->",
        "",
        "| Result | Value |",
        "|---|---|",
        f"| Planted experiment effects recovered inside the engine's 95 % CI | **{f['effects_covered']} / {f['effects_total']}** |",
        f"| SRM flagged only on the experiment with the planted bug, localised to Android | **{'yes' if f['srm_only_on_streak'] and f['srm_localised_android'] else 'no'}** |",
        f"| CUPED CI-width reduction on `paywall_redesign` | **{pct(f['cuped_ci_width_reduction'])}** (variance −{pct(f['cuped_variance_reduction'])}) |",
        f"| A/A false-positive rate: fixed horizon / naive peeking / mSPRT | {pct(f['fpr_fixed'])} / **{pct(f['fpr_naive'])}** / {pct(f['fpr_sequential'])} |",
        f"| D30 retention model PR-AUC (test) vs majority baseline | **{f['pr_auc_model']:.3f}** vs {f['pr_auc_majority']:.3f} (heuristic {f['pr_auc_heuristic']:.3f}) |",
        f"| Model recall at the validation-chosen threshold (v1: 0.000) | **{f['recall_model']:.3f}** |",
        f"| Planted retention drivers in the model's top 5 features | **{'all 3' if f['drivers_recovered'] else 'not all'}** |",
        f"| Cox hazard ratio for setting a reminder in the first 72 h | {f['cox_hr_reminder']:.3f} |",
        f"| AI analyst eval ({f['ai_n']} questions, `{f['ai_provider']}` provider): correct / SQL valid / refusals | {pct(f['ai_correct'], 0)} / {pct(f['ai_sql_valid'], 0)} / {pct(f['ai_refusal'], 0)} |",
        "",
        "| Experiment | Decision | Primary lift [95 % CI] | SRM p |",
        "|---|---|---|---:|",
        *exp_rows,
        END,
    ])


def main() -> int:
    readme = ROOT / "README.md"
    text = readme.read_text()
    pattern = re.compile(re.escape(START) + ".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        print("README has no RESULTS markers")
        return 1
    new = pattern.sub(lambda _: block(), text)
    if "--check" in sys.argv:
        ok = new == text
        print("README results match artifacts" if ok else "README results are STALE - run `make results`")
        return 0 if ok else 1
    readme.write_text(new)
    print("README results block updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
