"""Orchestrates: plan -> SQL -> guard -> run -> (retry once) -> explain -> log."""

from __future__ import annotations

import json
import numbers
import time
from datetime import UTC, datetime

import pandas as pd
from pydantic import BaseModel, Field

from pulseiq.config import get_settings
from pulseiq.services.db import cursor

from . import guard, offline, tools
from .llm import LLMClient, LLMError, get_client, parse_json
from .prompts import EXPLAIN_SYSTEM, system_prompt, user_prompt


class AnalystResponse(BaseModel):
    """What the analyst returns for a question."""

    question: str
    answer: str
    sql: str | None = None
    rows: list[dict] = Field(default_factory=list)
    columns: list[str] = Field(default_factory=list)
    chart_spec: dict = Field(default_factory=dict)
    caveats: list[str] = Field(default_factory=list)
    refused: bool = False
    error: str | None = None
    intent: str | None = None
    latency_ms: float = 0.0
    provider: str = "offline"
    retried: bool = False


def _fmt(col: str, v) -> str:
    if v is None or (isinstance(v, float) and pd.isna(v)):
        return "n/a"
    if isinstance(v, pd.Timestamp):
        return v.strftime("%Y-%m-%d") if v == v.normalize() else v.strftime("%Y-%m-%d %H:%M")
    if isinstance(v, numbers.Number) and not isinstance(v, bool):
        v = float(v)
        c = col.lower()
        if (
            any(k in c for k in ("rate", "retention", "stickiness", "share", "drop"))
            and abs(v) <= 1
        ):
            return f"{v:.1%}"
        if "usd" in c or "revenue" in c or "mrr" in c or "arppu" in c:
            return f"${v:,.2f}"
        return f"{v:,.0f}" if float(v).is_integer() else f"{v:,.3f}"
    return str(v)


def template_answer(df: pd.DataFrame, chart: dict) -> str:
    """Deterministic grounded summary of the result rows."""
    if df.empty or _all_null(df):
        return "No data matched this question in the available data (the warehouse covers 2025 signups only)."
    if len(df) == 1 and "drop_onboarded_to_trial" in df.columns:
        drops = {c: df.iloc[0][c] for c in df.columns if c.startswith("drop_")}
        worst = max(drops, key=drops.get)
        return (
            f"The biggest drop is {worst[5:].replace('_to_', ' → ').replace('_', ' ')}: "
            f"{_fmt(worst, drops[worst])} of users are lost at that step. "
            + "; ".join(f"{c.replace('_', ' ')}: {_fmt(c, df.iloc[0][c])}" for c in df.columns)
            + "."
        )
    if len(df) == 1:
        return (
            "; ".join(f"{c.replace('_', ' ')}: {_fmt(c, df.iloc[0][c])}" for c in df.columns) + "."
        )
    y = (
        chart.get("y")
        if chart.get("y") in df.columns
        else df.select_dtypes("number").columns[-1:].tolist()[0]
        if len(df.select_dtypes("number").columns)
        else None
    )
    x = chart.get("x") if chart.get("x") in df.columns else df.columns[0]
    if y is None:
        return f"{len(df)} rows returned."
    if chart.get("type") == "line":
        first, last = df.iloc[0], df.iloc[-1]
        return (
            f"{y.replace('_', ' ')} went from {_fmt(y, first[y])} ({first[x]}) to {_fmt(y, last[y])} ({last[x]}) "
            f"over {len(df)} points; peak {_fmt(y, df[y].max())}."
        )
    top = df.sort_values(y, ascending=False).iloc[0]
    bottom = df.sort_values(y, ascending=True).iloc[0]
    return (
        f"Highest {y.replace('_', ' ')}: {top[x]} at {_fmt(y, top[y])}; lowest: {bottom[x]} at "
        f"{_fmt(y, bottom[y])} ({len(df)} groups)."
    )


def _all_null(df: pd.DataFrame) -> bool:
    num = df.select_dtypes("number").drop(
        columns=[c for c in df.columns if c in ("days", "eligible_users")], errors="ignore"
    )
    return len(df) == 1 and num.shape[1] > 0 and bool(num.isna().all(axis=None))


def _caveats(df: pd.DataFrame, sql: str | None) -> list[str]:
    out = ["Synthetic data generated by PulseIQ; patterns are simulated."]
    if df is not None and (df.empty or _all_null(df)):
        out.append(
            "The warehouse covers 2025 signups only (see Data & Methods); the question's period may be outside it."
        )
    if sql and "retention" in sql.lower():
        out.append(
            "Retention counts only users whose day-N window is fully observed (immature cohorts excluded)."
        )
    if df is not None and len(df) > 1 and df.select_dtypes("number").shape[1]:
        out.append(
            "Differences between segments are descriptive, not causal, and not significance-tested."
        )
    return out


def _log(resp: AnalystResponse) -> None:
    d = get_settings().artifacts_dir / "ai_logs"
    try:
        d.mkdir(parents=True, exist_ok=True)
        rec = resp.model_dump(exclude={"rows"})
        rec["n_rows"] = len(resp.rows)
        rec["ts"] = datetime.now(UTC).isoformat(timespec="seconds")
        with (d / f"{datetime.now(UTC):%Y-%m-%d}.jsonl").open("a") as f:
            f.write(json.dumps(rec, default=str) + "\n")
    except OSError:
        pass


def _records(df: pd.DataFrame) -> list[dict]:
    return json.loads(df.head(guard.MAX_ROWS).to_json(orient="records", date_format="iso"))


def _run_tool(name: str, args: dict, resp: AnalystResponse) -> AnalystResponse:
    if name == "get_experiment_report":
        exp_id = args.get("experiment_id", "")
        try:
            df, answer, caveats = tools.get_experiment_report(exp_id)
        except KeyError:
            resp.answer, resp.refused = f"Unknown experiment '{exp_id}'.", True
            return resp
    elif name == "list_experiments":
        df, answer, caveats = tools.list_experiments()
    else:
        resp.answer, resp.refused = f"Unknown tool '{name}'.", True
        return resp
    resp.intent = name
    resp.answer, resp.caveats = answer, caveats
    resp.rows, resp.columns = _records(df), list(df.columns)
    resp.chart_spec = {"type": "table"}
    return resp


def ask(
    question: str, provider: str | None = None, client: LLMClient | None = None
) -> AnalystResponse:
    """Answer ``question``. ``client`` overrides ``provider`` (tests inject MockLLM)."""
    t0 = time.perf_counter()
    question = question.strip()[:1000]
    llm = client if client is not None else get_client(provider)
    resp = AnalystResponse(
        question=question, answer="", provider=llm.provider if llm else "offline"
    )
    try:
        if llm is None:
            p = offline.plan(question)
            plan = (
                {"refuse": p.refuse}
                if p.refuse
                else (
                    {"tool": p.tool, **p.tool_args}
                    if p.tool
                    else {"intent": p.intent, "sql": p.sql, "chart": p.chart, "notes": p.notes}
                )
            )
            raw = None
        else:
            raw = llm.complete(system_prompt(), user_prompt(question))
            plan = parse_json(raw)

        attempt = 0
        while True:
            if "refuse" in plan:
                resp.answer, resp.refused = str(plan["refuse"]), True
                break
            if "tool" in plan:
                resp = _run_tool(plan["tool"], plan, resp)
                break
            try:
                guarded = guard.validate(str(plan.get("sql", "")))
                with cursor() as cur:
                    df = guard.execute(cur, guarded)
            except guard.GuardError as e:
                if llm is None or attempt >= 1:
                    resp.answer, resp.refused, resp.error = (
                        f"I couldn't run a safe query: {e}",
                        True,
                        str(e),
                    )
                    resp.sql = plan.get("sql")
                    break
                attempt += 1
                resp.retried = True
                raw = llm.complete(system_prompt(), user_prompt(question, str(e), raw))
                plan = parse_json(raw)
                continue
            resp.intent = plan.get("intent")
            resp.sql = guarded.sql
            resp.chart_spec = plan.get("chart") or {}
            resp.rows, resp.columns = _records(df), list(df.columns)
            resp.caveats = _caveats(df, guarded.sql)
            answer = ""
            if llm is not None and llm.provider != "mock":
                try:
                    expl = parse_json(
                        llm.complete(
                            EXPLAIN_SYSTEM,
                            json.dumps(
                                {
                                    "question": question,
                                    "rows": resp.rows[:50],
                                    "columns": resp.columns,
                                },
                                default=str,
                            ),
                        )
                    )
                    answer = str(expl.get("answer", ""))
                    resp.caveats += [c for c in expl.get("caveats", []) if isinstance(c, str)]
                except (LLMError, json.JSONDecodeError):
                    answer = ""
            resp.answer = answer or template_answer(df, resp.chart_spec)
            if plan.get("notes"):
                resp.caveats.insert(0, str(plan["notes"]))
            break
    except (LLMError, json.JSONDecodeError) as e:
        resp.error = str(e)
        resp.answer = "The language model is unavailable; falling back to offline mode."
        fallback = ask(question, provider="offline")
        fallback.caveats.insert(0, f"LLM error ({e}); answered in offline mode.")
        return fallback
    resp.latency_ms = (time.perf_counter() - t0) * 1000
    _log(resp)
    return resp
